#!/usr/bin/env python3
"""Regenerate MobTypes.swift from locally installed, hash-checked official game jars."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import zipfile

VERSIONS = {
    "26.1": "java26_1", "26.1.1": "java26_1_1", "26.1.2": "java26_1_2",
    "26.2": "java26_2", "26.3": "java26_3",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("minecraft", type=Path)
    parser.add_argument("java_home", type=Path)
    parser.add_argument("evidence", type=Path, help="New directory for commands, raw facts and logs")
    parser.add_argument("--write", action="store_true", help="Replace generated Swift instead of checking it")
    args = parser.parse_args()
    args.evidence = args.evidence.resolve()
    args.evidence.mkdir(parents=True, exist_ok=False)
    here = Path(__file__).resolve().parent
    catalogs, provenance, classifications = {}, [], {}
    for version in VERSIONS:
        folder = args.minecraft / "versions" / version
        metadata = json.loads((folder / (version + ".json")).read_text())
        jar = folder / (version + ".jar")
        sha1 = hashlib.sha1(jar.read_bytes()).hexdigest()
        if sha1 != metadata["downloads"]["client"]["sha1"]:
            raise ValueError(f"Client hash mismatch: {version}")
        with zipfile.ZipFile(jar) as archive:
            game_version = json.loads(archive.read("version.json"))
        libraries = [args.minecraft / "libraries" / library["downloads"]["artifact"]["path"]
                     for library in metadata["libraries"] if "artifact" in library.get("downloads", {})]
        # Launcher metadata also lists native artifacts for other hosts. Only installed jars load.
        classpath = ":".join(str(p.resolve()) for p in [jar] + libraries if p.exists())
        output = args.evidence / version
        output.mkdir()
        commands = [
            [str(args.java_home / "bin/javac"), "-cp", classpath, "-d", str(output),
             str(here / "ExtractEntityTypes.java")],
            [str(args.java_home / "bin/java"), "-Djava.awt.headless=true", "-cp",
             str(output) + ":" + classpath, "ExtractEntityTypes", str(output / "entity-types.json")],
        ]
        (output / "commands.json").write_text(json.dumps({"sha1": sha1, "commands": commands}, indent=2) + "\n")
        for index, command in enumerate(commands):
            result = subprocess.run(command, cwd=output, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            (output / f"{index}.log").write_text(result.stdout)
            if result.returncode:
                raise RuntimeError(f"Extraction failed; see {output / f'{index}.log'}")
        entries = json.loads((output / "entity-types.json").read_text())
        for identifier, entry in entries.items():
            if not identifier.startswith("minecraft:"):
                raise ValueError(f"Non-vanilla registry entry: {identifier}")
            if classifications.setdefault(identifier, entry["mob"]) != entry["mob"]:
                raise ValueError(f"Classification changed: {version} {identifier}")
        catalogs[version] = {identifier.removeprefix("minecraft:"): entry["mob"]
                             for identifier, entry in entries.items()}
        provenance.append(f"// {version} / {game_version['world_version']}: {len(entries)} types, "
                          f"{sum(catalogs[version].values())} mobs; client SHA-1 {sha1}")
        print(provenance[-1])
    baseline = catalogs["26.3"]
    lines = ["// Generated by Tools/EntityTypes/generate.py. Do not edit the catalog by hand."] + provenance
    lines += ["", "/// Mob membership from Minecraft's registered types and their Java class ancestry.",
              "enum MobTypes {", "    /// True for a registered mob, false for a registered non-mob, nil for an unknown type.",
              "    static func membership(_ id: Identifier, dataVersion: Int?) -> Bool? {",
              '        guard id.namespace == "minecraft" else { return nil }',
              "        switch dataVersion {"]
    groups = {}
    for version, values in catalogs.items():
        if values != baseline:
            groups.setdefault(tuple(sorted(values.items())), []).append(version)
    for values, versions in groups.items():
        cases = ", ".join("SaveVersion." + VERSIONS[v] for v in versions)
        lines.append(f"        case {cases}: return {VERSIONS[versions[0]]}[id.path]")
    lines += ["        default: return java26_3[id.path]", "        }", "    }", "",
              "    // Like Minecraft, resolve known types through the reader's registry when the saved",
              "    // version has no catalog of its own. This does not grant version-specific defaults.",
              "    private static let java26_3: [String: Bool] = ["]
    lines += [f'        "{identifier}": {str(mob).lower()},' for identifier, mob in sorted(baseline.items())]
    lines += ["    ]"]
    for values, versions in groups.items():
        values = dict(values)
        expression = "java26_3"
        removed = baseline.keys() - values.keys()
        if removed:
            expression += ".filter { ![" + ", ".join(json.dumps(x) for x in sorted(removed)) + "].contains($0.key) }"
        added = values.keys() - baseline.keys()
        if added:
            expression += ".merging([" + ", ".join(f'{json.dumps(x)}: {str(values[x]).lower()}'
                                                   for x in sorted(added)) + "]) { _, new in new }"
        lines.append(f"    private static let {VERSIONS[versions[0]]} = {expression}")
    lines += ["}", ""]
    generated = "\n".join(lines)
    target = here.parents[1] / "Sources/ChunkseeKit/MobTypes.swift"
    (args.evidence / "MobTypes.swift").write_text(generated)
    if args.write:
        target.write_text(generated)
    elif not target.exists() or target.read_text() != generated:
        raise SystemExit("MobTypes.swift differs from the verified registry output")


if __name__ == "__main__":
    main()
