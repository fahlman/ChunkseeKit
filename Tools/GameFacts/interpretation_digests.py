"""Cache dependencies of the generated production facts, not a game-content catalog."""
import hashlib
import json


# Every generated production file must make an explicit choice. An empty tuple means that
# none of these four caches stores its result. New generated outputs fail until classified.
FACT_DOMAINS = {
    "DyeColor.swift": ("assets", "regionFacts"),
    "GeneratedMobAppearance.swift": ("regionFacts",),
    "GeneratedCreatureColors.swift": ("assets",),
    "GeneratedEnchantmentEffects.swift": ("assets", "regionFacts"),
    "GeneratedItemModelFacts.swift": ("assets", "regionFacts"),
    "GeneratedBlockDefaults.swift": ("terrain", "assets"),
    "GeneratedBlockModelSeeds.swift": ("assets",),
    "GeneratedBlockTints.swift": ("assets",),
    "GeneratedBlockFluids.swift": ("terrain", "assets"),
    "GeneratedAirBlocks.swift": ("terrain",),
    "GeneratedBlockEntityRenderers.swift": ("assets",),
    "GeneratedSpecialItemModels.swift": ("assets",),
    "GeneratedSpawnEggs.swift": ("assets",),
    "GeneratedBlockItems.swift": ("assets",),
    "GeneratedEquipmentFacts.swift": ("regionFacts",),
    "GeneratedTradingFacts.swift": ("assets", "regionFacts"),
    "GeneratedMobSpawnFacts.swift": ("assets",),
    "GeneratedStatisticUnits.swift": (),  # Player statistics are not persisted in these caches.
    "GeneratedPotionColors.swift": ("assets",),
    "GeneratedHealthDefaults.swift": ("regionFacts",),
    "GeneratedLightStorage.swift": ("light",),
    "GeneratedMapColors.swift": ("assets",),
    "GeneratedLegacyContentIDs.swift": ("assets", "regionFacts"),
    "GeneratedNonBlockDefinitions.swift": ("assets",),
    "GeneratedPortalFacts.swift": ("assets",),
    "GeneratedSaveRenames.swift": ("terrain", "assets", "regionFacts"),
    "GeneratedSavedText.swift": ("regionFacts",),
    "GeneratedLegacyChunkFacts.swift": ("terrain", "light", "regionFacts"),
}
DOMAINS = ("terrain", "light", "assets", "regionFacts")


def interpretation_digests(sources):
    prefix = "Sources/ChunkseeKit/"
    production = {path.removeprefix(prefix): value for path, value in sources.items()
                  if path.startswith(prefix)}
    if production.keys() != FACT_DOMAINS.keys():
        raise ValueError("Unclassified or missing generated facts: "
                         + ", ".join(sorted(production.keys() ^ FACT_DOMAINS.keys())))
    if any(set(domains) - set(DOMAINS) for domains in FACT_DOMAINS.values()):
        raise ValueError("Unknown interpretation domain")
    result = {}
    for domain in DOMAINS:
        values = {name: production[name] for name, domains in FACT_DOMAINS.items()
                  if domain in domains}
        # Hash exactly what ships, including the generator's interpretation of extracted data.
        # Proofs, source.json and tool/input provenance do not participate. A production-source
        # formatting change can conservatively retire a cache; it cannot preserve stale facts.
        data = json.dumps(values, sort_keys=True, ensure_ascii=False,
                          separators=(",", ":")).encode("utf-8")
        result[domain] = hashlib.sha256(data).hexdigest()
    return result


def interpretation_digest_source(sources):
    values = interpretation_digests(sources)
    source = "// Generated by Tools/GameFacts/regenerate.py. Provenance: Tools/GameFacts/source.json.\n"
    source += "// SHA-256 of each domain's generated production facts.\n"
    source += "enum GeneratedInterpretationDigests {\n"
    for domain, value in values.items():
        source += f'    static let {domain} = "{value}"\n'
    return {"Sources/ChunkseeKit/GeneratedInterpretationDigests.swift": source + "}\n"}
